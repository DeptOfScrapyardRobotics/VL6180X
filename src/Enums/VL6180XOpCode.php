<?php

namespace DeptOfScrapyardRobotics\Sensors\VL6180X\Enums;

/** 16-bit register indexes, sent high byte first. */
enum VL6180XOpCode: int
{
    case MODEL_ID = 0x000;

    case SYSTEM_MODE_GPIO1 = 0x011;
    case SYSTEM_INTERRUPT_CONFIG_GPIO = 0x014;
    case SYSTEM_INTERRUPT_CLEAR = 0x015;
    case SYSTEM_FRESH_OUT_OF_RESET = 0x016;

    case SYSRANGE_START = 0x018;
    case SYSRANGE_INTERMEASUREMENT_PERIOD = 0x01B;
    case SYSRANGE_VHV_RECALIBRATE = 0x02E;
    case SYSRANGE_VHV_REPEAT_RATE = 0x031;

    case SYSALS_INTERMEASUREMENT_PERIOD = 0x03E;
    case SYSALS_ANALOGUE_GAIN = 0x03F;
    case SYSALS_INTEGRATION_PERIOD = 0x040;

    case RESULT_RANGE_STATUS = 0x04D;
    case RESULT_INTERRUPT_STATUS_GPIO = 0x04F;
    case RESULT_RANGE_VAL = 0x062;

    case READOUT_AVERAGING_SAMPLE_PERIOD = 0x10A;
}
